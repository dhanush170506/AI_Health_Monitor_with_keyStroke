"""
AI Health Monitor - Model Training (Module 1)
=============================================

Trains the RandomForestClassifier used by the live monitoring pipeline.

HONESTY NOTE (important):
This is a HACKATHON PROTOTYPE. There is no clinically labelled dataset, so the
training data is SYNTHETIC: raw keyboard/mouse event windows are generated by
the behavioural event simulator in backend/demo_simulator.py (human-plausible
typing rhythm and target-seeking mouse motion), passed through the SAME
feature-extraction pipeline used live, and labelled by scenario:
slower / more variable behaviour -> FATIGUE, fast + corrective -> STRESS,
variable + jerky -> ANXIETY. Per-virtual-user offsets and window-to-window
noise make the classes genuinely overlap.

  * The resulting model is NOT clinically validated.
  * It is NOT a medical diagnostic model.
  * It exists to make the end-to-end demo pipeline realistic and responsive.

Classes: 0 = NORMAL, 1 = FATIGUE, 2 = STRESS, 3 = ANXIETY

Outputs:
  model/health_model.pkl      - trained RandomForest (joblib)
  model/feature_names.json    - canonical feature order for predictor.py
  model/training_report.json  - metrics printed below, also saved for the UI
"""
import json
import os
import sys

import numpy as np
import pandas as pd
from joblib import dump
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
from sklearn.model_selection import train_test_split

# Ensure we can import the backend package no matter where this is run from.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from backend.feature_engine import FEATURE_NAMES, extract_features  # noqa: E402
from backend import demo_simulator  # noqa: E402

RANDOM_SEED = 42
SAMPLES_PER_CLASS = 360          # 4 classes -> 1440 samples total
USERS_PER_CLASS = 15             # virtual users; windows per user = 24
TEST_SIZE = 0.25

CLASS_NAMES = {0: "NORMAL", 1: "FATIGUE", 2: "STRESS", 3: "ANXIETY"}
SCENARIO_FOR_CLASS = {0: "normal", 1: "fatigue", 2: "stress", 3: "anxiety"}


def generate_dataset(n_per_class=SAMPLES_PER_CLASS, seed=RANDOM_SEED,
                     users_per_class=USERS_PER_CLASS):
    """Generate the synthetic behavioural dataset.

    For every virtual user we draw a personal behavioural offset (some people
    type fast & sloppy, others slow & precise), then simulate several
    30-60 s keyboard/mouse windows for their assigned condition. Raw events go
    through the SAME extract_features() pipeline used in live monitoring.
    Per-user offsets + window noise make the classes genuinely overlap.
    """
    rng = np.random.default_rng(seed)
    windows_per_user = max(1, n_per_class // users_per_class)
    rows = []

    for cls in range(4):
        scenario = SCENARIO_FOR_CLASS[cls]
        for _user in range(users_per_class):
            personal = {f: float(rng.lognormal(0.0, 0.11)) for f in FEATURE_NAMES}
            for _w in range(windows_per_user):
                duration = float(rng.choice([30_000.0, 45_000.0, 60_000.0]))
                # severity in [0.2, 1.0]: many windows sit near the NORMAL
                # boundary -> genuine class overlap (believable accuracy).
                severity = float(rng.uniform(0.2, 1.0))
                keys, mouse, acq = demo_simulator.generate(scenario,
                                                           duration_ms=duration,
                                                           severity=severity)
                n_err, n_chars = demo_simulator.error_counts(scenario,
                                                             n_events=len(keys),
                                                             severity=severity)
                vec, _meta = extract_features(keys, mouse, duration / 1000.0,
                                              n_chars_typed=n_chars, n_errors=n_err,
                                              target_acquisitions=acq)
                row = {}
                for f in FEATURE_NAMES:
                    value = vec[f] * personal[f] * float(rng.lognormal(0.0, 0.05))
                    row[f] = max(value, 0.0)
                rows.append(row)

    df = pd.DataFrame(rows)
    df["target"] = np.repeat(np.arange(4), users_per_class * windows_per_user)[:len(df)]
    return df


def main():
    print("=" * 70)
    print("AI HEALTH MONITOR - TRAINING (synthetic behavioural prototype data)")
    print("NOT clinically validated. NOT a medical diagnostic model.")
    print("=" * 70)

    df = generate_dataset()
    X = df[FEATURE_NAMES].values
    y = df["target"].values

    print(f"\nDataset size: {len(df)} samples x {len(FEATURE_NAMES)} features")
    print("Class distribution:")
    for cls, name in CLASS_NAMES.items():
        print(f"  {cls} {name:8s}: {(y == cls).sum()}")

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=TEST_SIZE, random_state=RANDOM_SEED, stratify=y)

    model = RandomForestClassifier(
        n_estimators=200,
        max_depth=12,
        min_samples_leaf=4,
        class_weight="balanced",
        random_state=RANDOM_SEED,
        n_jobs=-1,
    )
    model.fit(X_train, y_train)

    train_acc = accuracy_score(y_train, model.predict(X_train))
    test_acc = accuracy_score(y_test, model.predict(X_test))
    y_pred = model.predict(X_test)

    print(f"\nTraining accuracy: {train_acc:.3f}")
    print(f"Testing  accuracy: {test_acc:.3f}")
    print("\nClassification report:")
    print(classification_report(y_test, y_pred,
                                target_names=[CLASS_NAMES[i] for i in sorted(CLASS_NAMES)]))
    print("Confusion matrix (rows = true, cols = predicted):")
    cm = confusion_matrix(y_test, y_pred)
    header = "        " + "  ".join(f"{CLASS_NAMES[i]:>8s}" for i in sorted(CLASS_NAMES))
    print(header)
    for i, row in enumerate(cm):
        print(f"  {CLASS_NAMES[i]:>7s} " + "  ".join(f"{v:8d}" for v in row))

    # ---- persist -----------------------------------------------------------
    os.makedirs("model", exist_ok=True)
    dump(model, os.path.join("model", "health_model.pkl"))
    with open(os.path.join("model", "feature_names.json"), "w", encoding="utf-8") as f:
        json.dump(FEATURE_NAMES, f, indent=2)

    report = {
        "trained_at": __import__("datetime").datetime.now().isoformat(timespec="seconds"),
        "note": "Synthetic behavioural data. NOT clinically validated. "
                "NOT a medical diagnostic model.",
        "n_samples": int(len(df)),
        "n_features": len(FEATURE_NAMES),
        "class_distribution": {CLASS_NAMES[c]: int((y == c).sum()) for c in CLASS_NAMES},
        "train_accuracy": round(float(train_acc), 4),
        "test_accuracy": round(float(test_acc), 4),
        "confusion_matrix": cm.tolist(),
        "class_names": [CLASS_NAMES[i] for i in sorted(CLASS_NAMES)],
    }
    with open(os.path.join("model", "training_report.json"), "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    print("\nSaved: model/health_model.pkl")
    print("Saved: model/feature_names.json")
    print("Saved: model/training_report.json")
    print("Done.")


if __name__ == "__main__":
    main()
